import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const state = readFileSync(new URL('lib/client-state.js', root), 'utf8').replace(/^export /gm, '');
const entry = readFileSync(new URL('src/client-entry.js', root), 'utf8').replace(/^import .*;\n/gm, '').replace(/^export /gm, '');
const bundle = `// Generated by scripts/build.mjs. Source: lib/client-state.js + src/client-entry.js.\nwindow.__ModuleLoader__.load({id:'dsh-next-message',factory(require){\nconst React=require('react');\n${state}\n${entry}\nreturn createClient(React);\n}});\n`;
writeFileSync(new URL('client.js', root), bundle);
for (const file of ['client.js', ...readdirSync(new URL('lib/', root)).filter(f => f.endsWith('.js')).map(f => `lib/${f}`)]) execFileSync(process.execPath, ['--check', fileURLToPath(new URL(file, root))]);
console.log('Client bundle built; JavaScript syntax checks passed.');
